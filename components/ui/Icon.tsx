export interface IconProps extends Omit<React.SVGProps<SVGSVGElement>, 'color' | 'name' | 'ref' | 'strokeWidth' | 'size' | 'weight'> {
  name?: string;
  className?: string;
  size?: number | string;
  color?: string;
  /** Hugeicons has one stroke style, so 'bold' and 'fill' only make the stroke heavier. */
  weight?: 'thin' | 'light' | 'regular' | 'bold' | 'fill' | 'duotone';
  title?: string;
  strokeWidth?: number | string;
  style?: React.CSSProperties;
}

export const Icon: React.FC<IconProps> = ({
  name,
  className = '',
  size,
  color = 'currentColor',
  weight,
  strokeWidth,
  style,
  ...props
}) => {
  if (!name) return null;

  // Resolve the key from the legacy map or a direct match
  const cleanName = name.trim();
  const normalizedName = cleanName.replace(/Icon$/i, '');
  const pascalName = normalizedName.replace(/(^[a-z]|[_\-\s]+([a-z0-9]))/gi, (_, p1, p2) => (p2 || p1).toUpperCase());

  const resolvedKey =
    ICON_NAME_MAP[cleanName] ||
    ICON_NAME_MAP[cleanName.toLowerCase()] ||
    ICON_NAME_MAP[normalizedName] ||
    ICON_NAME_MAP[normalizedName.toLowerCase()] ||
    ICON_NAME_MAP[pascalName] ||
    cleanName;

  const resolvedPascalKey = resolvedKey.replace(/Icon$/i, '').replace(/(^[a-z]|[_\-\s]+([a-z0-9]))/gi, (_, p1, p2) => (p2 || p1).toUpperCase());

  const icon =
    ICONS[resolvedPascalKey] ||
    ICONS[resolvedKey] ||
    ICONS[pascalName] ||
    ICONS[normalizedName] ||
    ICONS[cleanName] ||
    ICONS.SquaresFour;

  // Standardize sizing: If no explicit width/height in className or size prop, default to inline text scaling (1em x 1em)
  const hasWidthClass = /\b(w-\d+|w-\[.*\]|w-full|w-screen|w-auto|size-\d+|size-\[.*\])\b/.test(className);
  const hasHeightClass = /\b(h-\d+|h-\[.*\]|h-full|h-screen|h-auto|size-\d+|size-\[.*\])\b/.test(className);

  const defaultSizeClass = !hasWidthClass && !hasHeightClass && !size ? 'w-[1em] h-[1em]' : '';

  return (
    <HugeiconsIcon
      icon={icon}
      className={`shrink-0 block ${defaultSizeClass} ${className}`.trim()}
      size={size ?? '1em'}
      color={color}
      strokeWidth={Number(strokeWidth ?? (weight === 'bold' || weight === 'fill' ? 2 : 1.5))}
      style={style}
      {...(props as Record<string, unknown>)}
    />
  );
};

/** A fixed icon as a component, for libraries that take an icon component. */
export const createIcon = (name: string): React.FC<Omit<IconProps, 'name'>> => {
  const Fixed: React.FC<Omit<IconProps, 'name'>> = (props) => <Icon name={name} {...props} />;
  Fixed.displayName = `Icon(${name})`;
  return Fixed;
};

export default Icon;
