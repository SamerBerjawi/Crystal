test('quote + privacy probe', async ({ authedPage: page, user }) => {
  test.skip((page.viewportSize()?.width ?? 0) < 768);
  await goTo(page, '/invoices');
  await page.getByRole('button', { name: 'Draft Quote' }).first().click();
  await page.getByPlaceholder('e.g. Acme Corp or Jane Doe').fill('QA Quote Client');
  await page.getByPlaceholder(/item or service descriptio/i).first().fill('QA consulting');
  const nums = page.locator('div.fixed input[type="number"][required]'); await nums.nth(0).fill('2'); await nums.nth(1).fill('150');
  console.log('QUOTE submit buttons:', (await page.locator('div.fixed button:visible').allInnerTexts()).slice(-4).join(' | '));
  await page.locator('div.fixed button[type="submit"]:visible').last().click(); await page.waitForTimeout(2500);
  const q = (await serverData(user)).invoices.filter((i: any) => JSON.stringify(i).includes('QA Quote Client'));
  console.log('AFTER DRAFT:', JSON.stringify(q.map((d: any) => ({ type: d.type, status: d.status, number: d.number || d.invoiceNumber }))));
  await page.getByRole('button', { name: /^proposals/i }).first().click().catch(() => {});
  await page.waitForTimeout(500);
  const conv = page.getByRole('button', { name: /convert to invoice/i }).first();
  console.log('convert buttons:', await page.getByRole('button', { name: /convert to invoice/i }).count());
  await conv.click(); await page.waitForTimeout(2500);
  const q2 = (await serverData(user)).invoices.filter((i: any) => JSON.stringify(i).includes('QA Quote Client'));
  console.log('AFTER CONVERT:', JSON.stringify(q2.map((d: any) => ({ type: d.type, status: d.status, number: d.number || d.invoiceNumber }))));
  await goTo(page, '/accounts');
  const amt = page.locator('main').getByText(/3,450\.75/).first();
  const before = await amt.evaluate(e => ({ t: (e as HTMLElement).innerText, f: getComputedStyle(e).filter, cls: e.className }));
  await page.getByRole('button', { name: /privacy mode/i }).first().click(); await page.waitForTimeout(600);
  const anyAmount = await page.locator('main').innerText();
  console.log('PRIVACY before:', JSON.stringify(before), '| after still shows 3,450.75?', /3,450\.75/.test(anyAmount), '| masked chars?', /•{2,}|\*{3,}/.test(anyAmount));
  const blurCount = await page.locator('main *').evaluateAll(es => es.filter(e => /blur/.test(getComputedStyle(e).filter)).length);
  console.log('elements with blur filter:', blurCount);
});
